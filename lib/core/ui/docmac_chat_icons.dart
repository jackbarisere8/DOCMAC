/// Shared paths for the monochrome action glyphs used by Talk and Chat.
///
/// These assets match the fine line weight of Docmac's wider icon system so
/// message actions (reply, forward, copy and more) feel native to the product.
abstract final class DocmacChatIcons {
  static const _path = 'assets/icons/chat/';

  static const reply = '${_path}reply.svg';
  static const forward = '${_path}forward.svg';
  static const copy = '${_path}copy.svg';
  static const more = '${_path}more.svg';
}
